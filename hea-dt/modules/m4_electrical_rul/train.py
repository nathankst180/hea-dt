"""
modules/m4_electrical_rul/train.py

Trains M4's two models from data/battery_dataset.parquet and
data/motor_dataset.parquet (generated by data/generate_fault_data.py):

  1. A LightGBM regressor predicting battery_rul_s_true (seconds until the
     internal-resistance failure threshold — R_FAIL_OHM in
     data/generate_fault_data.py) from BATTERY_FEATURE_NAMES.
  2. A LightGBM classifier predicting whether a given motor is "weak"
     (efficiency-degraded) from MOTOR_FEATURE_NAMES.

battery_soh_pct is deliberately NOT a third trained model — see
predictor.py's docstring: it's derived at inference time directly from
twin.battery_internal_resistance_ohm via the same closed-form formula the
dataset's ground truth uses. Training a second regressor to reproduce a
known deterministic function would add nothing.

Splits come from the dataset's own `split` column (assigned per-FLIGHT by
the generator, not per-row, so sequential correlation within a flight
can't leak across train/val/test).

Run:
    python -m modules.m4_electrical_rul.train
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import lightgbm as lgb
import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, f1_score, mean_absolute_error, mean_squared_error

from config.loader import load_config
from modules.m4_electrical_rul.features import BATTERY_FEATURE_NAMES, MOTOR_FEATURE_NAMES

_LGBM_PARAMS = dict(n_estimators=200, max_depth=6, learning_rate=0.05, num_leaves=31, random_state=0, verbosity=-1)


def _split(df: pd.DataFrame, name: str) -> pd.DataFrame:
    return df[df["split"] == name]


def train_battery_rul(df: pd.DataFrame) -> tuple[lgb.LGBMRegressor, dict]:
    train, val, test = _split(df, "train"), _split(df, "val"), _split(df, "test")

    model = lgb.LGBMRegressor(**_LGBM_PARAMS)
    model.fit(train[BATTERY_FEATURE_NAMES], train["battery_rul_s_true"])

    metrics: dict = {}
    for split_name, split_df in (("val", val), ("test", test)):
        preds = model.predict(split_df[BATTERY_FEATURE_NAMES])
        y = split_df["battery_rul_s_true"]
        metrics[f"battery_rul_rmse_s_{split_name}"] = float(np.sqrt(mean_squared_error(y, preds)))
        metrics[f"battery_rul_mae_s_{split_name}"] = float(mean_absolute_error(y, preds))

        # The overall number above is diluted: 5 of our 6 scenarios have a
        # CONSTANT "no failure" label (NO_FAILURE_TTF_S), so a model that
        # just predicts that constant for non-degrading inputs already
        # scores well on most rows. The number that actually answers "how
        # good is the RUL prediction" is restricted to the aging_battery
        # rows, where the label is a real, varying countdown — report that
        # separately rather than let it hide inside the diluted average.
        aging_mask = split_df["scenario"] == "aging_battery"
        if aging_mask.any():
            y_aging = y[aging_mask]
            preds_aging = preds[aging_mask.to_numpy()]
            metrics[f"battery_rul_rmse_s_{split_name}_aging_battery_only"] = float(
                np.sqrt(mean_squared_error(y_aging, preds_aging))
            )
            metrics[f"battery_rul_mae_s_{split_name}_aging_battery_only"] = float(
                mean_absolute_error(y_aging, preds_aging)
            )
    metrics["battery_n_train"] = int(len(train))
    return model, metrics


def train_motor_weak_classifier(df: pd.DataFrame) -> tuple[lgb.LGBMClassifier, dict]:
    train, val, test = _split(df, "train"), _split(df, "val"), _split(df, "test")

    model = lgb.LGBMClassifier(**_LGBM_PARAMS)
    model.fit(train[MOTOR_FEATURE_NAMES], train["motor_weak_true"])

    metrics: dict = {}
    for split_name, split_df in (("val", val), ("test", test)):
        preds = model.predict(split_df[MOTOR_FEATURE_NAMES])
        y = split_df["motor_weak_true"]
        metrics[f"motor_weak_accuracy_{split_name}"] = float(accuracy_score(y, preds))
        metrics[f"motor_weak_f1_{split_name}"] = float(f1_score(y, preds))
    metrics["motor_n_train"] = int(len(train))
    return model, metrics


def main() -> None:
    config = load_config("config/config.yaml")
    data_dir = Path(config.paths.data_dir)
    models_dir = Path(config.paths.models_dir)
    models_dir.mkdir(parents=True, exist_ok=True)
    results_dir = Path("results")
    results_dir.mkdir(parents=True, exist_ok=True)

    battery_df = pd.read_parquet(data_dir / "battery_dataset.parquet")
    motor_df = pd.read_parquet(data_dir / "motor_dataset.parquet")
    print(f"battery_dataset: {len(battery_df)} rows, motor_dataset: {len(motor_df)} rows")

    battery_model, battery_metrics = train_battery_rul(battery_df)
    print("battery RUL regressor:")
    for k, v in battery_metrics.items():
        print(f"  {k}: {v}")

    motor_model, motor_metrics = train_motor_weak_classifier(motor_df)
    print("motor weak classifier:")
    for k, v in motor_metrics.items():
        print(f"  {k}: {v}")

    joblib.dump(battery_model, models_dir / "m4_battery_rul.joblib")
    joblib.dump(motor_model, models_dir / "m4_motor_weak.joblib")

    metrics = {**battery_metrics, **motor_metrics}
    metrics_path = results_dir / "m4_metrics.json"
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"\nSaved models to {models_dir}/")
    print(f"Saved metrics to {metrics_path}")


if __name__ == "__main__":
    main()
