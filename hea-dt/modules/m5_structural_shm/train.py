"""
modules/m5_structural_shm/train.py

Trains M5's models from data/structural_dataset.parquet (generated by
data/generate_fault_data.py):

  1. A RandomForestClassifier predicting imbalance_true (prop_imbalance vs.
     every other scenario, including healthy AND the other fault types —
     high_wind and sensor_glitch in particular are included as negatives
     specifically so they don't get mistaken for structural problems)
     from the spectral features in features.py. Random Forest on spectral
     features is the primary model here because that's what Gemayel et
     al. (2024) and Rao et al. (2025) found worked best for this exact
     problem (rotor-imbalance detection from vibration spectra).
  2. A RandomForestRegressor predicting prop_damage_true (severity mapped
     to 0-1) from the same features, for a continuous severity estimate
     rather than just a flag.

Reports accuracy, F1, AND false-alarm rate (false positive rate: how
often a NON-imbalance flight gets flagged) — the false-alarm rate matters
more than accuracy alone here, since the negative class includes
deliberately confusable scenarios (high_wind's attitude jitter, sensor
glitches) precisely to stress-test it.

Run:
    python -m modules.m5_structural_shm.train
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import pandas as pd
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, mean_absolute_error

from config.loader import load_config
from modules.m5_structural_shm.features import FEATURE_NAMES

ROTOR_CORR_NAMES = [f"rotor_corr_{i}" for i in range(4)]
ALL_FEATURE_NAMES = FEATURE_NAMES + ROTOR_CORR_NAMES


def _split(df: pd.DataFrame, name: str) -> pd.DataFrame:
    return df[df["split"] == name]


def _false_alarm_rate(y_true, y_pred) -> float:
    """False positive rate: of the truly-negative (non-imbalance) rows,
    what fraction got flagged as imbalance anyway."""
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return float(fp / (fp + tn)) if (fp + tn) > 0 else 0.0


def train_imbalance_classifier(df: pd.DataFrame) -> tuple[RandomForestClassifier, dict]:
    train, val, test = _split(df, "train"), _split(df, "val"), _split(df, "test")

    model = RandomForestClassifier(n_estimators=200, max_depth=10, random_state=0, n_jobs=1, class_weight="balanced")
    model.fit(train[ALL_FEATURE_NAMES], train["imbalance_true"])

    metrics: dict = {}
    for split_name, split_df in (("val", val), ("test", test)):
        preds = model.predict(split_df[ALL_FEATURE_NAMES])
        y = split_df["imbalance_true"]
        metrics[f"imbalance_accuracy_{split_name}"] = float(accuracy_score(y, preds))
        metrics[f"imbalance_f1_{split_name}"] = float(f1_score(y, preds))
        metrics[f"imbalance_false_alarm_rate_{split_name}"] = _false_alarm_rate(y, preds)

        # False-alarm rate restricted to the scenarios most likely to be
        # confused with real imbalance (environmental/sensor noise, not a
        # structural problem) — the number that actually matters for "is
        # this classifier trustworthy in practice", not just overall FPR
        # which is diluted by the easy healthy-vs-imbalance cases.
        confusable = split_df[split_df["scenario"].isin(["high_wind", "sensor_glitch"])]
        if len(confusable) > 0:
            confusable_preds = model.predict(confusable[ALL_FEATURE_NAMES])
            metrics[f"imbalance_false_alarm_rate_{split_name}_confusable_only"] = _false_alarm_rate(
                confusable["imbalance_true"], confusable_preds
            )
    metrics["imbalance_n_train"] = int(len(train))
    return model, metrics


def train_damage_regressor(df: pd.DataFrame) -> tuple[RandomForestRegressor, dict]:
    train, val, test = _split(df, "train"), _split(df, "val"), _split(df, "test")

    model = RandomForestRegressor(n_estimators=200, max_depth=10, random_state=0, n_jobs=1)
    model.fit(train[ALL_FEATURE_NAMES], train["prop_damage_true"])

    metrics: dict = {}
    for split_name, split_df in (("val", val), ("test", test)):
        preds = model.predict(split_df[ALL_FEATURE_NAMES])
        metrics[f"prop_damage_mae_{split_name}"] = float(mean_absolute_error(split_df["prop_damage_true"], preds))
    return model, metrics


def main() -> None:
    config = load_config("config/config.yaml")
    data_dir = Path(config.paths.data_dir)
    models_dir = Path(config.paths.models_dir)
    models_dir.mkdir(parents=True, exist_ok=True)
    results_dir = Path("results")
    results_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_parquet(data_dir / "structural_dataset.parquet")
    print(f"structural_dataset: {len(df)} rows")
    print("imbalance_true balance:\n", df.groupby("split")["imbalance_true"].mean().to_string())

    clf, clf_metrics = train_imbalance_classifier(df)
    print("imbalance classifier:")
    for k, v in clf_metrics.items():
        print(f"  {k}: {v}")

    reg, reg_metrics = train_damage_regressor(df)
    print("damage severity regressor:")
    for k, v in reg_metrics.items():
        print(f"  {k}: {v}")

    joblib.dump(clf, models_dir / "m5_imbalance_classifier.joblib")
    joblib.dump(reg, models_dir / "m5_damage_regressor.joblib")

    metrics = {**clf_metrics, **reg_metrics}
    metrics_path = results_dir / "m5_metrics.json"
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"\nSaved models to {models_dir}/")
    print(f"Saved metrics to {metrics_path}")


if __name__ == "__main__":
    main()
